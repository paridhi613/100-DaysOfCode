fruit = "mango"
len =  len(fruit)    #len finction is used to find the length of the string
print("length of mango is ", len)

#slicing 
print(fruit[0:3])   #man 
print(fruit[1:4])   #ang
print(fruit[2:])    #ngo
print(fruit[:4])   #mang
print(fruit[:])    #mango



print(fruit[-1])   #o
print(fruit[-2])   #g
#the negative indexing starts from the end and moves to the start

print(fruit[-3:-1])   #an